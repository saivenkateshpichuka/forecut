def build(dept, cat, it):
    name, note, area = it['name'], it['note'], it['area']
    txt = (name + ' ' + note).lower()
    noun = CAT_NOUN.get(cat, cat.lower())
    over = note.rstrip('.') + '. ' + AREA.get(area, 'A focused detail update for ' + noun + '.')
    tips, fab = [], None
    for pat, tip, f in RULES:
        if re.search(pat, txt):
            if tip and len(tips) < 2 and tip not in tips: tips.append(tip)
            if f and not fab: fab = f
    for t in AREA_TIP.get(area, []):
        if len(tips) < 3: tips.append(t)
    if fab and fab.startswith(('YKK', 'Horn-effect')): fab = CAT_FAB.get(cat, '') + ' Trims: ' + fab[0].lower() + fab[1:]
    if not fab: fab = CAT_FAB.get(cat, '')
    use = 'Best on ' + CAT_USE.get(dept + '|' + cat, noun) + '. Works in ' + dept.lower() + (' ' + noun if dept != 'Footwear' else '') + ' as a capsule hero or as a quiet update to core styles.'
    if dept == 'Footwear': use = 'Best on ' + CAT_USE.get(dept + '|' + cat, noun) + '. Use it as a capsule hero or as a quiet update to core styles.'
    d = {'o': over, 'd': tips, 'f': fab, 'u': use}
    if isinstance(it.get('desc'), dict): d.update(it['desc'])
    return d
