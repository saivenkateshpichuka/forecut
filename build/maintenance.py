"""Forecasts maintenance mode. When content/settings.json has "forecasts_maintenance": true, every forecast library page
(forecasts.html and forecasts/**) shows a maintenance notice inside the normal site header and footer. URLs keep working;
redirect stubs are left alone. Set the flag to false and rebuild to restore the pages (they are regenerated by the build)."""
import json, os, re, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = json.load(open(os.path.join(ROOT, 'content', 'settings.json')))
if not S.get('forecasts_maintenance'):
    raise SystemExit(0)

BODY = '''<main id="main">
<section style="max-width:760px;margin:0 auto;padding:120px 24px 140px;text-align:center">
<p style="margin:0;font-size:14px;color:#5b6662">Forecasts</p>
<h1 style="margin:16px 0 0;font-size:48px;line-height:1.1;font-weight:400">We are rebuilding the forecast library</h1>
<p style="margin:20px auto 0;font-size:18px;line-height:1.6;color:#3e4a46;max-width:600px">Forecut forecasts are being redesigned with richer trend, key item, colour and materials research and a weekly update. The library will be back soon.</p>
<p style="margin:28px 0 0;font-size:16px;line-height:1.6">Questions or early access: <a href="mailto:hello@forecut.in">hello@forecut.in</a></p>
<p style="margin:28px 0 0"><a href="/" style="display:inline-block;padding:12px 22px;border-radius:999px;background:#1f3a33;color:#fff;text-decoration:none">Back to home</a> <a href="/insights" style="display:inline-block;margin-left:8px;padding:12px 22px;border-radius:999px;border:1px solid #1f3a33;color:#1f3a33;text-decoration:none">Read Insights</a></p>
</section>
</main>'''

files = [os.path.join(ROOT, 'forecasts.html')] + glob.glob(os.path.join(ROOT, 'forecasts', '**', '*.html'), recursive=True)
n = 0
for f in files:
    if not os.path.isfile(f):
        continue
    h = open(f, encoding='utf-8').read()
    if 'location.replace' in h and '<main' not in h:
        continue  # redirect stub
    m = re.search(r'<main[^>]*>.*?</main>', h, re.S)
    if not m:
        continue
    h = h[:m.start()] + BODY + h[m.end():]
    h = re.sub(r'<title>.*?</title>', '<title>Forecasts: back soon | Forecut</title>', h, count=1, flags=re.S)
    if 'name="robots"' not in h:
        h = h.replace('</head>', '<meta name="robots" content="noindex">\n</head>', 1)
    else:
        h = re.sub(r'<meta name="robots"[^>]*>', '<meta name="robots" content="noindex">', h, count=1)
    open(f, 'w', encoding='utf-8').write(h)
    n += 1
print('forecasts maintenance: pages replaced', n)
